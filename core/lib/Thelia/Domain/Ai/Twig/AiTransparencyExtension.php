namespace Thelia\Domain\Ai\Twig;

use Thelia\Domain\Ai\AiProvenance;
use Thelia\Domain\Ai\AiUsageRegistryInterface;
use Thelia\Domain\Ai\Service\AiTextTranslator;
use Twig\Extension\AbstractExtension;
use Twig\TwigFunction;

/**
 * The transparency tools of the AI Act for templates: the notice "you are talking with an AI" (article 50(1))
 * and the machine-readable mark of a generated content (article 50(2)). They render nothing visual of their own:
 * the theme decides where and how the notice and the label look.
 *
 * Nothing here needs a request: they work the same when a mail is rendered from the console.
 */
final class AiTransparencyExtension extends AbstractExtension
{
    /** The attribute that carries the mark; the value of each field of the stored mark goes in its own attribute. */
    public const string ATTRIBUTE_FLAG = 'data-ai-generated';

    public function __construct(
        private readonly AiUsageRegistryInterface $usages,
        private readonly AiTextTranslator $translator,
    ) {
    }

    public function getFunctions(): array
    {
        return [
            new TwigFunction('ai_transparency_notice', $this->transparencyNotice(...)),
            new TwigFunction('ai_provenance_attributes', $this->provenanceAttributes(...), ['is_safe' => ['html']]),
            new TwigFunction('ai_provenance_label', $this->provenanceLabel(...)),
        ];
    }

    /**
     * The notice of an interactive usage in the current language, an empty string when there is nothing to show
     * (usage not interactive or inactive, notice turned off by the merchant). Twig escapes the text; nothing
     * but a usage identifier unknown to the registry throws, so a typo is not a silent missing notice.
     */
    public function transparencyNotice(string $usageId, ?string $locale = null): string
    {
        return $this->usages->transparencyNotice($usageId, $locale) ?? '';
    }

    /**
     * The attributes to put on the element that holds a generated content, for a machine to read:
     * `data-ai-generated="true" data-ai-usage="…" data-ai-model="…" data-ai-generated-at="…"`.
     * Pass what the module stored: the array or the JSON of AiProvenance::toArray(), or the AiProvenance.
     * An empty string when it is not a valid mark.
     *
     * @param array<string, mixed>|string|AiProvenance|null $provenance
     */
    public function provenanceAttributes(array|string|AiProvenance|null $provenance): string
    {
        $mark = self::mark($provenance);

        if (null === $mark) {
            return '';
        }

        $values = [
            self::ATTRIBUTE_FLAG => 'true',
            'data-ai-usage' => $mark->usageId,
            'data-ai-model' => $mark->model,
            'data-ai-generated-at' => $mark->generatedAt->format(\DATE_ATOM),
        ];

        return implode(' ', array_map(
            static fn (string $name, string $value): string => \sprintf('%s="%s"', $name, htmlspecialchars($value, \ENT_QUOTES | \ENT_SUBSTITUTE)),
            array_keys($values),
            $values,
        ));
    }

    /**
     * A sentence a person can read next to a generated content, an empty string when there is no valid mark.
     *
     * @param array<string, mixed>|string|AiProvenance|null $provenance
     */
    public function provenanceLabel(array|string|AiProvenance|null $provenance, ?string $locale = null): string
    {
        $mark = self::mark($provenance);

        if (null === $mark) {
            return '';
        }

        return $this->translator->trans('Content generated by an AI (%model%) on %date%.', [
            '%model%' => $mark->model,
            '%date%' => $mark->generatedAt->format('Y-m-d'),
        ], $locale);
    }

    /**
     * @return list<string> the English source texts, to check they are all in the catalogs
     */
    public static function sources(): array
    {
        return ['Content generated by an AI (%model%) on %date%.'];
    }

    /**
     * @param array<string, mixed>|string|AiProvenance|null $provenance
     */
    private static function mark(array|string|AiProvenance|null $provenance): ?AiProvenance
    {
        return $provenance instanceof AiProvenance ? $provenance : AiProvenance::fromStored($provenance);
    }
}
