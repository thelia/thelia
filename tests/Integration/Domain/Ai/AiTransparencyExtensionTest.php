namespace Thelia\Tests\Integration\Domain\Ai;

use AiProbeModule\ProbeWriter;
use Psr\Log\NullLogger;
use Symfony\Component\HttpFoundation\RequestStack;
use Thelia\Domain\Ai\AiProvenance;
use Thelia\Domain\Ai\AiUsageRegistryInterface;
use Thelia\Domain\Ai\Repository\AiUsageSettingRepository;
use Thelia\Domain\Ai\Service\AiSettings;
use Thelia\Domain\Ai\Service\AiTextTranslator;
use Thelia\Domain\Ai\Service\AiUsageRegistry;
use Thelia\Domain\Ai\Twig\AiTransparencyExtension;
use Thelia\Domain\Localization\Service\LangService;
use Thelia\Model\AiUsageSetting;
use Thelia\Model\AiUsageSettingQuery;
use Thelia\Test\IntegrationTestCase;
use Twig\Environment;
use Twig\Loader\ArrayLoader;

/**
 * The Twig functions run here without any request: the way a mail is rendered from the console.
 */
final class AiTransparencyExtensionTest extends IntegrationTestCase
{
    public static function setUpBeforeClass(): void
    {
        require_once \dirname(__DIR__, 3).'/fixtures/ai/ProbeModule/ProbeWriter.php';
    }

    public function testTheNoticeIsRenderedWithoutARequestAndIsEmptyWhenTurnedOff(): void
    {
        $this->setting('aiprobe.chat', notice: true);

        $twig = $this->twig($this->realRegistry());
        $template = "{{ ai_transparency_notice('aiprobe.chat', 'fr_FR') }}";

        self::assertSame('Vous échangez avec un assistant IA. Ses réponses peuvent comporter des erreurs.', $twig->createTemplate($template)->render());

        $this->setting('aiprobe.chat', notice: false);

        self::assertSame('', $twig->createTemplate($template)->render());
    }

    public function testTheNoticeIsEscaped(): void
    {
        $registry = new class extends AiUsageRegistry {
            public function __construct()
            {
            }

            public function transparencyNotice(string $usageId, ?string $locale = null): ?string
            {
                return '<script>alert("x")</script> & co';
            }
        };

        self::assertSame('&lt;script&gt;alert(&quot;x&quot;)&lt;/script&gt; &amp; co', $this->twig($registry)->createTemplate("{{ ai_transparency_notice('a.b') }}")->render());
    }

    public function testTheMarkIsRenderedAsDataAttributesFromAStoredArrayOrJson(): void
    {
        $stored = (new AiProvenance('theliacms.page_generation', 'claude-"opus"', new \DateTimeImmutable('2026-10-28T10:15:00+00:00'), 9001))->toArray();
        $twig = $this->twig($this->realRegistry());
        $expected = 'data-ai-generated="true" data-ai-usage="theliacms.page_generation" data-ai-model="claude-&quot;opus&quot;" data-ai-generated-at="2026-10-28T10:15:00+00:00"';

        self::assertSame('<div '.$expected.'>x</div>', $twig->createTemplate('<div {{ ai_provenance_attributes(mark) }}>x</div>')->render(['mark' => $stored]));
        self::assertSame($expected, $twig->createTemplate('{{ ai_provenance_attributes(mark) }}')->render(['mark' => json_encode($stored)]));
    }

    public function testNothingIsRenderedForAMissingOrInvalidMark(): void
    {
        $twig = $this->twig($this->realRegistry());

        self::assertSame('', $twig->createTemplate('{{ ai_provenance_attributes(null) }}{{ ai_provenance_attributes("{nope") }}{{ ai_provenance_label(null) }}')->render());
    }

    public function testTheLabelIsTranslated(): void
    {
        $stored = (new AiProvenance('theliacms.page_generation', 'claude-opus-5-5', new \DateTimeImmutable('2026-10-28T10:15:00+00:00'), 9001))->toArray();
        $twig = $this->twig($this->realRegistry());

        self::assertSame('Contenu généré par une IA (claude-opus-5-5) le 2026-10-28.', $twig->createTemplate("{{ ai_provenance_label(mark, 'fr_FR') }}")->render(['mark' => $stored]));
        self::assertSame('Content generated by an AI (claude-opus-5-5) on 2026-10-28.', $twig->createTemplate("{{ ai_provenance_label(mark, 'en_US') }}")->render(['mark' => $stored]));
    }

    private function realRegistry(): AiUsageRegistryInterface
    {
        return new AiUsageRegistry(['aiprobe.chat' => ProbeWriter::class, 'aiprobe.writing' => ProbeWriter::class], new AiUsageSettingRepository(), new AiSettings());
    }

    private function twig(AiUsageRegistryInterface $registry): Environment
    {
        $twig = new Environment(new ArrayLoader(), ['autoescape' => 'html']);
        $twig->addExtension(new AiTransparencyExtension($registry, new AiTextTranslator(new LangService(new RequestStack(), new NullLogger()))));

        return $twig;
    }

    private function setting(string $usageId, bool $notice): void
    {
        $setting = AiUsageSettingQuery::create()->findOneByUsageId($usageId) ?? (new AiUsageSetting())->setUsageId($usageId);
        $setting->setMonthlyBudget('5')->setTransparencyNotice($notice)->save();
    }
}
